-- =====================================================
-- V6: 조회 경로 인덱스
--
-- [왜 지금인가]
-- C4에서 "상태 + 실행일 구간 + 금액"을 조합하는 대출 검색 화면이 생겼다.
-- 인덱스는 "느려서 붙이는 것"이 아니라 "어떤 질의가 주 경로인지 확정됐을 때" 붙인다.
--
-- [컬럼 순서의 근거]
-- 복합 인덱스는 왼쪽부터 순서대로만 쓸 수 있고, **범위 조건을 만나는 순간 그 뒤 컬럼은
-- 더 이상 탐색 범위를 좁히지 못한다**. 그래서 등치 조건(member_id, status)을 앞에,
-- 범위 조건(executed_at)을 마지막에 둔다. 순서를 바꾸면 인덱스를 타도 효과가 반감된다.
--
-- [주의] member_id에는 FK(fk_loan_acc_member) 때문에 이미 단일 인덱스가 있다.
-- 하지만 한 회원이 많은 대출을 가지면 그 인덱스로는 회원의 대출 "전부"를 훑은 뒤
-- status·기간을 필터로 걸러야 한다. 복합 인덱스는 그 걸러내기를 인덱스 단계에서 끝낸다.
-- =====================================================

-- 대출 검색의 주 경로: 본인(member_id) + 상태 + 실행일 구간
CREATE INDEX idx_loan_accounts_member_status_executed
    ON loan_accounts (member_id, status, executed_at);

-- 연체 감지 배치(D단계)의 주 경로: "납기 지난 PENDING 회차"를 매일 밤 훑는다.
-- 배치 코드보다 인덱스를 먼저 까는 이유는, 배치가 도는 시점에 이미 스케줄 행이
-- 대출 건수 × 회차수만큼 쌓여 있기 때문이다(대출 10만 건 × 12회차 = 120만 행).
CREATE INDEX idx_repayment_schedules_status_due
    ON repayment_schedules (status, due_date);
